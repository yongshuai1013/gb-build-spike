#!/usr/bin/env python3
"""Regenerate the ARM EABI syscall stubs of a GB 2.3.7 bionic tree so
that every stub passes through the M1 compat dispatcher
(__gb_gate_pre/__gb_gate_post in libc/arch-arm/bionic/gb_gate.c.arm).

The checked-in stubs under libc/arch-arm/syscalls/ are what the build
actually compiles (gensyscalls.py is only the developer tool that
produced them), so both are patched: this script rewrites the .S
files, and patches/bionic/0001 also updates gensyscalls.py's two EABI
templates with the identical text so a future regeneration keeps the
gate.

Usage: regen-gate-stubs.py <bionic-dir> [--check]

Skipped stubs (kept byte-identical to stock, see patches/README.md):
  __sys_clone - the svc returns on a *different* stack in the child,
                so no post-svc stack frame may be touched; thread
                creation uses the handwritten clone.S anyway.
  vfork       - child shares the parent's address space until exec;
                dispatcher bookkeeping is not vfork-safe.
"""
import os
import re
import sys

SKIP = {"__sys_clone", "vfork"}

HEADER = """/* autogenerated by gensyscalls.py + gb-gate (M1 compat dispatch) */
#include <sys/linux-syscalls.h>

    .text
    .type %(fname)s, #function
    .globl %(fname)s
    .align 4

%(fname)s:
"""

# Gate sequence shared by both templates once the 8-entry argument
# array has been built at [sp, #0..#28]:
#   [sp,#32] = skip-result slot, [sp,#36] = action, [sp,#40] = result,
#   [sp,#44] = syscall number. Frame: 20 bytes of saved registers plus
#   a 52-byte locals block keep sp 8-byte aligned at the bl calls.
GATE_TAIL = """\
    ldr     r0, =%(idname)s
    str     r0, [sp, #44]
    mov     r1, sp
    add     r2, sp, #32
    bl      __gb_gate_pre
    str     r0, [sp, #36]
    tst     r0, #1
    bne     20f
    ldr     r0, [sp, #0]
    ldr     r1, [sp, #4]
    ldr     r2, [sp, #8]
    ldr     r3, [sp, #12]
    ldr     r4, [sp, #16]
    ldr     r5, [sp, #20]
    ldr     r6, [sp, #24]
    ldr     r7, [sp, #44]
    swi     #0
    str     r0, [sp, #40]
    b       30f
20:
    ldr     r0, [sp, #32]
    str     r0, [sp, #40]
30:
    ldr     r3, [sp, #36]
    tst     r3, #2
    bne     40f
    ldr     r2, [sp, #40]
    mov     r1, sp
    ldr     r0, [sp, #44]
    bl      __gb_gate_post
    b       50f
40:
    ldr     r0, [sp, #40]
50:
    add     sp, sp, #52
    ldmfd   sp!, {r4, r5, r6, r7, lr}
    movs    r0, r0
    bxpl    lr
    b       __set_syscall_errno
"""

DEFAULT_BODY = """\
    ldr     ip, =__gb_gate_mode
    ldrb    ip, [ip]
    cmp     ip, #2
    beq     10f
    stmfd   sp!, {r4, r5, r6, r7, lr}
    sub     sp, sp, #52
    str     r0, [sp, #0]
    str     r1, [sp, #4]
    str     r2, [sp, #8]
    str     r3, [sp, #12]
    str     r4, [sp, #16]
    str     r5, [sp, #20]
    mov     ip, #0
    str     ip, [sp, #24]
    str     ip, [sp, #28]
""" + GATE_TAIL + """\
10:
    stmfd   sp!, {r4, r7}
    ldr     r7, =%(idname)s
    swi     #0
    ldmfd   sp!, {r4, r7}
    movs    r0, r0
    bxpl    lr
    b       __set_syscall_errno
"""

LONG_BODY = """\
    ldr     ip, =__gb_gate_mode
    ldrb    ip, [ip]
    cmp     ip, #2
    beq     10f
    mov     ip, sp
    stmfd   sp!, {r4, r5, r6, r7, lr}
    sub     sp, sp, #52
    str     r0, [sp, #0]
    str     r1, [sp, #4]
    str     r2, [sp, #8]
    str     r3, [sp, #12]
    ldr     r4, [ip, #0]
    str     r4, [sp, #16]
    ldr     r4, [ip, #4]
    str     r4, [sp, #20]
    ldr     r4, [ip, #8]
    str     r4, [sp, #24]
    mov     ip, #0
    str     ip, [sp, #28]
""" + GATE_TAIL + """\
10:
    mov     ip, sp
    stmfd   sp!, {r4, r5, r6, r7}
    ldmfd   ip, {r4, r5, r6}
    ldr     r7, =%(idname)s
    swi     #0
    ldmfd   sp!, {r4, r5, r6, r7}
    movs    r0, r0
    bxpl    lr
    b       __set_syscall_errno
"""


def transform(text):
    m = re.search(r"\.globl\s+(\S+)", text)
    fname = m.group(1)
    m = re.search(r"ldr\s+r7, =(__NR_\S+)", text)
    idname = m.group(1)
    if fname in SKIP:
        return None
    is_long = "ldmfd   ip" in text or "ldmfd\tip" in text
    t = {"fname": fname, "idname": idname}
    body = LONG_BODY if is_long else DEFAULT_BODY
    return (HEADER + body) % t


def main():
    bionic = sys.argv[1]
    check = "--check" in sys.argv
    sdir = os.path.join(bionic, "libc", "arch-arm", "syscalls")
    changed, skipped, already = 0, 0, 0
    for name in sorted(os.listdir(sdir)):
        if not name.endswith(".S"):
            continue
        path = os.path.join(sdir, name)
        text = open(path).read()
        if "__gb_gate_pre" in text:
            already += 1
            continue
        out = transform(text)
        if out is None:
            skipped += 1
            continue
        if check:
            print("WOULD CHANGE", name)
        else:
            open(path, "w").write(out)
        changed += 1
    print("changed=%d skipped=%d already=%d" % (changed, skipped, already))


if __name__ == "__main__":
    main()
